    private string[][] allMazes;

    private void Awake()
    {
        allMazes = new string[][]
        {
            maze01, maze02, maze03, maze04, maze05,
            maze06, maze07, maze08, maze09, maze10
        };
    }

    private void Start()
    {
        GenerateCellsIfNeeded();
        ApplyMaze(allMazes[currentMazeIndex]);
        StartCoroutine(MazeLoop());
    }

    [ContextMenu("Generate Cells")]
    public void GenerateCellsIfNeeded()
    {
        if (cellsParent == null)
        {
            GameObject parentObj = new GameObject("Cells");
            parentObj.transform.SetParent(transform);
            parentObj.transform.localPosition = Vector3.zero;
            cellsParent = parentObj.transform;
        }

        cells = new MazeCell[size, size];

        for (int i = 0; i < cellsParent.childCount; i++)
        {
            MazeCell existing = cellsParent.GetChild(i).GetComponent<MazeCell>();
            if (existing == null) continue;

            string[] parts = existing.name.Split('_');
            if (parts.Length == 3 &&
                int.TryParse(parts[1], out int x) &&
                int.TryParse(parts[2], out int z))
            {
                if (x >= 0 && x < size && z >= 0 && z < size)
                {
                    existing.upY = upY;
                    existing.downY = downY;
                    existing.moveSpeed = moveSpeed;
                    cells[x, z] = existing;
                }
            }
        }

        for (int z = 0; z < size; z++)
        {
            for (int x = 0; x < size; x++)
            {
                if (cells[x, z] != null) continue;

                GameObject cellObj = GameObject.CreatePrimitive(PrimitiveType.Cube);
                cellObj.name = $"Cell_{x}_{z}";
                cellObj.transform.SetParent(cellsParent);
                cellObj.transform.localPosition = new Vector3(x * cellSpacing, downY, z * cellSpacing);
                cellObj.transform.localScale = cellScale;

                MazeCell cell = cellObj.AddComponent<MazeCell>();
                cell.upY = upY;
                cell.downY = downY;
                cell.moveSpeed = moveSpeed;

                cells[x, z] = cell;
            }
        }
    }

    private IEnumerator MazeLoop()
    {
        yield return new WaitForSeconds(firstDelay);

        while (true)
        {
            yield return new WaitForSeconds(changeInterval);

            currentMazeIndex++;
            if (currentMazeIndex >= allMazes.Length)
                currentMazeIndex = 0;

            ApplyMaze(allMazes[currentMazeIndex]);
        }
    }

    [ContextMenu("Apply Current Maze")]
    public void ApplyCurrentMaze()
    {
        if (cells == null || cells.Length == 0)
            GenerateCellsIfNeeded();

        ApplyMaze(allMazes[currentMazeIndex]);
    }

    [ContextMenu("Next Maze")]
    public void NextMaze()
    {
        if (cells == null || cells.Length == 0)
            GenerateCellsIfNeeded();

        currentMazeIndex++;
        if (currentMazeIndex >= allMazes.Length)
            currentMazeIndex = 0;

        ApplyMaze(allMazes[currentMazeIndex]);
    }

    public void ApplyMaze(string[] map)
    {
        if (map == null || map.Length != size)
        {
            Debug.LogError($"미로 크기가 size({size})와 맞지 않음");
            return;
        }

        for (int z = 0; z < size; z++)
        {
            if (map[z].Length != size)
            {
                Debug.LogError($"미로 한 줄 길이가 {size}가 아님: {z}");
                return;
            }
        }

        for (int z = 0; z < size; z++)
        {
            for (int x = 0; x < size; x++)
            {
                char c = map[size - 1 - z][x];
                bool isWall = c == '#';

                if (cells[x, z] != null)
                    cells[x, z].SetWall(isWall);
            }
        }
    }
